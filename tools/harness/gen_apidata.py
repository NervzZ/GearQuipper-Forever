"""Generate tools/harness/data/apidata.lua from Blizzard's generated API documentation.

Usage: python gen_apidata.py <path to Blizzard_APIDocumentationGenerated>

The documentation folder comes from the WoW Forever UI source (Gethe/wow-ui-source, branch `forever`).
The output holds every documented event (with payload names), every documented function name, and every
enumeration, so the mock can (1) reject unknown events like the real client, (2) build `Enum` exactly,
and (3) tell "documented API the mock lacks" from "API that does not exist on Forever" in error reports.
"""
import os
import sys

from lupa import lua51

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "data", "apidata.lua")

COLLECT = r"""
local docs = {}
-- a few docs reference Enum.X.Y / Constants.X.Y values; any number will do for name extraction
local any = setmetatable({}, { __index = function(t) return t end, __call = function() return 0 end })
local anyMeta = { __index = function() return 0 end }
Enum = setmetatable({}, { __index = function() return setmetatable({}, anyMeta) end })
Constants = Enum
APIDocumentation = { AddDocumentationTable = function(self, t) docs[#docs + 1] = t end }
return docs
"""


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def flags(entry):
    """Restriction / secret flags of a documented function or event, e.g. "HasRestrictions SecretInChatMessagingLockdown"."""
    found = []
    for key, value in entry.items():
        if isinstance(key, str) and (key == "HasRestrictions" or key.startswith("Secret")) and key != "SecretArguments" and value:
            found.append(key if value is True else f"{key}={value}")
    return " ".join(sorted(found))


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    doc_dir = sys.argv[1]
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    docs = lua.execute(COLLECT)
    for fn in sorted(os.listdir(doc_dir)):
        if fn.endswith(".lua"):
            with open(os.path.join(doc_dir, fn), encoding="utf-8") as fh:
                chunk = lua.eval("loadstring")(fh.read(), "@" + fn)
            if chunk:
                chunk()

    events, functions, enums, widget_methods = {}, {}, {}, set()
    for t in docs.values():
        system_ns = t["Namespace"]
        for f in (t["Functions"] or {}).values():
            if t["Type"] == "ScriptObject":  # widget / object methods, not globals
                widget_methods.add(f["Name"])
                continue
            ns = f["Namespace"] if f["Namespace"] is not None else system_ns
            functions[f"{ns}.{f['Name']}" if ns else f["Name"]] = flags(f)
        for e in (t["Events"] or {}).values():
            payload = [p["Name"] for p in (e["Payload"] or {}).values()]
            events[e["LiteralName"]] = (payload, flags(e))
        for tab in (t["Tables"] or {}).values():
            if tab["Type"] == "Enumeration":
                enums[tab["Name"]] = [(fld["Name"], fld["EnumValue"]) for fld in (tab["Fields"] or {}).values()]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated by tools/harness/gen_apidata.py from Blizzard_APIDocumentationGenerated "
                  "(WoW Forever UI source). Do not edit.\n")
        out.write("return {\nevents = {\n")
        for name in sorted(events):
            payload, fl = events[name]
            items = [lua_str(p) for p in payload] + ([f"flags = {lua_str(fl)}"] if fl else [])
            out.write(f"  {name} = {{{', '.join(items)}}},\n")
        out.write("},\nfunctions = {\n")
        for name in sorted(functions):
            value = lua_str(functions[name]) if functions[name] else "true"
            out.write(f"  [{lua_str(name)}] = {value},\n")
        out.write("},\nwidgetMethods = {\n")
        for name in sorted(widget_methods):
            out.write(f"  {name} = true,\n")
        out.write("},\nenums = {\n")
        for name in sorted(enums):
            fields = ", ".join(f"[{lua_str(k)}] = {int(v)}" for k, v in enums[name])
            out.write(f"  {name} = {{{fields}}},\n")
        out.write("},\n}\n")
    print(f"wrote {OUT}: {len(events)} events, {len(functions)} functions, {len(widget_methods)} widget methods, "
          f"{len(enums)} enums")


if __name__ == "__main__":
    main()
